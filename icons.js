// Writes scss/_callout-icons.scss from callout-icons.txt (a callout type and its Lucide icon per line),
// fetching each icon from Lucide once. Run it through icons.sh after editing the list, and commit the result.
const pairs = Deno.readTextFileSync("callout-icons.txt").split("\n").filter((l) => l.trim()).map((l) => l.trim().split(/\s+/));
const bodies = {};
for (const icon of [...new Set(pairs.map(([, i]) => i))].sort()) {
  const svg = await (await fetch(`https://unpkg.com/lucide-static/icons/${icon}.svg`)).text();
  bodies[icon] = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].replace(/\s*\n\s*/g, "").replaceAll('"', "'");
}
const rows = pairs.map(([type, icon]) => `\t"${type}": "${bodies[icon]}"`);
Deno.writeTextFileSync("scss/_callout-icons.scss", "// Generated by icons.sh from callout-icons.txt. Do not edit.\n$icons: (\n" + rows.join(",\n") + "\n);\n");
console.log(pairs.length, "callouts,", Object.keys(bodies).length, "icons");
